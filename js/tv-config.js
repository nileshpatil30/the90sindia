/* ==========================================================================
   90s REWIND TV — CHANNEL BUILDER
   ==========================================================================
   You normally do NOT edit this file. The timetable lives in
   js/tv-schedule.js (one row per show: network, years, day, time). This file
   reads that table and builds one channel for every network and year, e.g.
   "DD National 1992" or "Zee TV 1997", each with its own fixed weekly
   timetable of the shows that really aired there that year.

   WHERE THE VIDEOS COME FROM
     - js/tv-library.js   one row per show: a YouTube playlist ID, or a list
                          of single video IDs with their real episode numbers
     - js/tv-episodes.js  longer hand-checked lists (Ramayan, Hum Paanch,
                          Shaktimaan, Rangoli, Cartoon Network, ...)
   A schedule row finds its videos by the show name (or by eps: 'NAME').
   Episode 1 plays in the week of TV_EPOCH, then one new episode a week, in
   order. A show with several slots a week plays consecutive episodes.

   COMMERCIALS (ads): your own clips, played between shows and to fill gaps.
     { title, sponsor, duration (SECONDS), video: "" }
     Leave video empty to show a "commercial break" card (default).
     NEVER overlay or cover YouTube's own ads: only use these slots.

   HOW TO GET A YOUTUBE VIDEO ID: from youtube.com/watch?v=XXXXXXXXXXX the ID
   is the part after v=. Prefer official rights-holder channels (DD National /
   Prasar Bharati, Zee, Star, Cartoon Network, Tilak). Where none exists,
   community uploads are used; they can be taken down or blocked by the
   uploader at any time, so re-check now and then.
   ========================================================================== */

// ---- episode sources -------------------------------------------------------
var EP_RAMAYAN = (typeof RAMAYAN_TILAK !== 'undefined') ? RAMAYAN_TILAK : [];
var EP_HUMPAANCH = (typeof HUM_PAANCH_ZEE !== 'undefined') ? HUM_PAANCH_ZEE : [];
var EP_HUMPAANCH_NUMS = (typeof HUM_PAANCH_NUMS !== 'undefined') ? HUM_PAANCH_NUMS : [];
var EP_RANGOLI = (typeof RANGOLI_DD !== 'undefined') ? RANGOLI_DD : [];
var EP_RANGOLI_NUMS = (typeof RANGOLI_NUMS !== 'undefined') ? RANGOLI_NUMS : [];
var EP_SHAKTI = (typeof SHAKTIMAAN_ULTRA !== 'undefined') ? SHAKTIMAAN_ULTRA : [];
var EP_SHAKTI_NUMS = (typeof SHAKTIMAAN_NUMS !== 'undefined') ? SHAKTIMAAN_NUMS : [];
var EP_CN = (typeof CARTOON_NETWORK_30 !== 'undefined') ? CARTOON_NETWORK_30 : [];
var EP_KBC = (typeof KBC_S1_COMMUNITY !== 'undefined') ? KBC_S1_COMMUNITY : [];
var EP_CHITRAHAAR = (typeof CHITRAHAAR_COMMUNITY !== 'undefined') ? CHITRAHAAR_COMMUNITY : [];
var EP_MAHABHARAT = (typeof MAHABHARAT_DM !== 'undefined') ? MAHABHARAT_DM : [];
var EP_MAHABHARAT_NUMS = (typeof MAHABHARAT_NUMS !== 'undefined') ? MAHABHARAT_NUMS : [];

function eps(ids) { return ids.map(function (v) { return { video: v }; }); }
// "id1 id2 id3" or "id1, id2" or an array -> array
function words(x) { return Array.isArray(x) ? x : String(x || '').split(/[\s,]+/).filter(Boolean); }
// Episodes / numbers of a show in js/tv-library.js, for putting it in a fixed timetable slot.
function libRow(title) {
  var lib = (typeof TV_LIBRARY !== 'undefined') ? TV_LIBRARY : [];
  for (var i = 0; i < lib.length; i++) { if (lib[i].title === title) return lib[i]; }
  return null;
}
function libEps(title) { var r = libRow(title); return r && r.episodes ? eps(words(r.episodes)) : []; }
function libNums(title) { var r = libRow(title); return r && r.nums ? words(r.nums).map(Number) : false; }

// Named, hand-checked episode sets that a schedule row can ask for with eps: 'NAME'.
var EPISODE_SETS = {
  RAMAYAN:    { episodes: eps(EP_RAMAYAN),    nums: undefined,          official: false },
  RANGOLI:    { episodes: eps(EP_RANGOLI),    nums: EP_RANGOLI_NUMS,    official: true },
  CHITRAHAAR: { episodes: eps(EP_CHITRAHAAR), nums: false,              official: false },
  HUM_PAANCH: { episodes: eps(EP_HUMPAANCH),  nums: EP_HUMPAANCH_NUMS,  official: true },
  SHAKTIMAAN: { episodes: eps(EP_SHAKTI),     nums: EP_SHAKTI_NUMS,     official: true },
  KBC:        { episodes: eps(EP_KBC),        nums: false,              official: false },
  MAHABHARAT: { episodes: EP_MAHABHARAT,      nums: EP_MAHABHARAT_NUMS.length ? EP_MAHABHARAT_NUMS : false, official: false }
};

// Ad breaks, idents and continuity recordings per channel: js/tv-ads.js.
var AD_PACKS = (typeof TV_AD_PACKS !== 'undefined') ? TV_AD_PACKS : {};

// Fallback commercial rotation (plain cards) for a channel with no ad pack. Your own clips can go here.
var TV_ADS = [
  { title: 'Commercial break', sponsor: 'Your 90s ad here', duration: 30, video: '' },
  { title: 'Commercial break', sponsor: 'Sponsor this break', duration: 30, video: '' },
  { title: 'Commercial break', sponsor: 'Your 90s ad here', duration: 20, video: '' }
];

function adsFor(netId) { var a = AD_PACKS[netId]; return (a && a.length) ? a : TV_ADS; }

// Doordarshan switched off at night: a test card shows in this window.
var DD_CLOSEDOWN = { from: '23:30', to: '06:30', label: 'Transmission has ended for the day' };

// ---- build channels from the schedule ---------------------------------------
var DAY_ORDER = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

function daysOf(d) {
  var list;
  if (d === 'daily') list = DAY_ORDER.slice();
  else if (d === 'weekdays') list = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri'];
  else if (d === 'weekend') list = ['Sat', 'Sun'];
  else list = Array.isArray(d) ? d.slice() : [d];
  return list.sort(function (a, b) { return DAY_ORDER.indexOf(a) - DAY_ORDER.indexOf(b); });
}

var _srcCache = {};
// Where a schedule row gets its episodes: a named set, or the library row.
function episodeSource(run) {
  var key = run.eps || run.lib || run.show;
  if (_srcCache[key]) return _srcCache[key];
  var out;
  if (run.eps && EPISODE_SETS[run.eps]) {
    out = EPISODE_SETS[run.eps];
  } else {
    var row = libRow(run.lib || run.show);
    if (!row) out = { episodes: [], nums: false, playlist: null, official: false };
    else if (row.episodes) out = { episodes: eps(words(row.episodes)), nums: row.nums ? words(row.nums).map(Number) : false, playlist: null, official: !!row.official };
    else out = { episodes: [], nums: false, playlist: row.playlist, official: !!row.official };
  }
  _srcCache[key] = out;
  return out;
}

// Cartoon Network: real blocks were 3-5 pm weekdays, 2-4 pm weekends. Split into
// 30-minute slots so each slot plays different cartoons from the official uploads.
function cnSlots(run) {
  var out = [], n = 0;
  ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'].forEach(function (d) {
    var start = (d === 'Sat' || d === 'Sun') ? 14 * 60 : 15 * 60;
    for (var k = 0; k < 4; k++, n++) {
      var t = start + k * 30, shift = n % Math.max(1, EP_CN.length);
      var rot = EP_CN.slice(shift).concat(EP_CN.slice(0, shift));
      out.push({ day: d, time: ('0' + Math.floor(t / 60)).slice(-2) + ':' + ('0' + (t % 60)).slice(-2), duration: 30,
        title: run.show, episodes: eps(rot), epNums: false, startDate: TV_EPOCH,
        confidence: run.conf, source: run.src, official: true });
    }
  });
  return out;
}

function slotsFor(runs) {
  var slots = [];
  runs.forEach(function (r) {
    if (r.gen === 'cn') { cnSlots(r).forEach(function (s) { slots.push(s); }); return; }
    var src = episodeSource(r), days = daysOf(r.day);
    days.forEach(function (d, i) {
      slots.push({
        day: d, time: r.time, duration: r.dur, title: r.show,
        episodes: src.episodes, playlist: src.playlist || undefined, epNums: src.nums,
        startDate: TV_EPOCH, epOffset: i, epStep: days.length,   // consecutive episodes across a week's slots
        confidence: r.conf, source: r.src, fixture: !!r.fixture, official: !!src.official
      });
    });
  });
  return slots;
}

function buildChannels(nets, runs) {
  var out = [];
  nets.forEach(function (net) {
    for (var y = TV_YEARS.from; y <= TV_YEARS.to; y++) {
      var here = runs.filter(function (r) { return r.net === net.id && r.from <= y && y <= r.to; });
      if (!here.length) continue;
      var names = [];
      here.forEach(function (r) { if (!r.fixture && names.indexOf(r.show) < 0) names.push(r.show); });
      out.push({
        num: net.id + '-' + y, net: net.id, year: y,
        name: net.name, short: net.short, era: String(y),
        tag: names.slice(0, 4).join(', ') + (names.length > 4 ? ' and ' + (names.length - 4) + ' more' : ''),
        tz: 330, ads: adsFor(net.id), closedown: net.closedown ? DD_CLOSEDOWN : null,
        slots: slotsFor(here)
      });
    }
  });
  return out;
}

var TV_CHANNELS = (typeof TV_RUNS !== 'undefined' ? buildChannels(TV_NETS, TV_RUNS) : []);

/* ---- THE ALL SHOWS CATALOGUE ------------------------------------------------
   One entry per watchable show, built from the library, the hand-checked episode
   sets and the ad packs, with the timetable slots it appears in. The ALL SHOWS
   section of the page (js/tv-shows.js) lists these.
     { id, title, kind, official, note, years, nets: [ids], runs: [ {net,from,to,day,time,conf,fixture} ],
       episodes: [video ids], nums: [numbers]|false, labels: [text]|null, playlist: 'PL...'|null }            */
var EPSET_META = {
  RAMAYAN: { title: 'Ramayan', kind: 'religious' }, RANGOLI: { title: 'Rangoli', kind: 'music' }, CHITRAHAAR: { title: 'Chitrahaar', kind: 'music' },
  HUM_PAANCH: { title: 'Hum Paanch', kind: 'comedy' }, SHAKTIMAAN: { title: 'Shaktimaan', kind: 'fantasy' }, KBC: { title: 'Kaun Banega Crorepati', kind: 'music' },
  MAHABHARAT: { title: 'Mahabharat', kind: 'religious' }
};

function buildShows(nets, runs) {
  var by = {}, list = [];
  function get(title) {
    if (!by[title]) { by[title] = { id: '', title: title, kind: 'other', official: false, note: '', years: '', nets: [], runs: [], episodes: [], nums: false, labels: null, playlist: null }; list.push(by[title]); }
    return by[title];
  }
  (typeof TV_LIBRARY !== 'undefined' ? TV_LIBRARY : []).forEach(function (r) {
    var s = get(r.title);
    s.kind = r.kind || 'other'; s.official = !!r.official; s.note = r.note || ''; s.years = r.years || '';
    if (r.net) s.nets = [r.net];
    if (r.episodes) { s.episodes = words(r.episodes); s.nums = r.nums ? words(r.nums).map(Number) : false; }
    else if (r.playlist) s.playlist = r.playlist;
  });
  runs.forEach(function (r) {
    if (r.gen === 'cn') {
      var c = get(r.show); c.kind = 'kids'; c.official = true; c.episodes = EP_CN.slice(); c.note = c.note || 'Cartoon Network India\'s own uploads.';
      c.runs.push({ net: r.net, from: r.from, to: r.to, conf: r.conf, fixture: false });
      return;
    }
    var s = get(r.show), set = r.eps && EPISODE_SETS[r.eps];
    if (set && set.episodes.length && !s.episodes.length && !s.playlist) {
      s.episodes = set.episodes.map(function (e) { return e.video; });
      s.nums = (set.nums && set.nums.length) ? set.nums : false;
      s.official = !!set.official;
      s.kind = (EPSET_META[r.eps] || {}).kind || s.kind;
    }
    s.runs.push({ net: r.net, from: r.from, to: r.to, day: r.day, time: r.time, conf: r.conf, fixture: !!r.fixture });
  });
  // ad breaks, idents and continuity: one watchable entry per channel
  var netName = {}; nets.forEach(function (n) { netName[n.id] = n.name; });
  Object.keys(AD_PACKS).forEach(function (id) {
    var seen = {}, vids = [], labels = [];
    AD_PACKS[id].forEach(function (a) { if (a.video && !seen[a.video]) { seen[a.video] = 1; vids.push(a.video); labels.push(a.sponsor); } });
    if (!vids.length) return;
    var s = get((netName[id] || id) + ': ad breaks and idents');
    s.kind = 'ads'; s.official = false; s.episodes = vids; s.labels = labels; s.nets = [id];
    s.note = 'The recordings that play between shows on this channel: 90s ad breaks, idents and continuity, uploaded by TV-archive collectors.';
  });
  list = list.filter(function (s) { return s.episodes.length || s.playlist; });
  list.forEach(function (s) {
    s.runs.forEach(function (r) { if (s.nets.indexOf(r.net) < 0) s.nets.push(r.net); });
    s.id = s.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  });
  list.sort(function (a, b) {
    var x = a.title.replace(/^(the|a)\s+/i, '').toLowerCase(), y = b.title.replace(/^(the|a)\s+/i, '').toLowerCase();
    return x < y ? -1 : x > y ? 1 : 0;
  });
  return list;
}

var TV_SHOWS = (typeof TV_RUNS !== 'undefined' ? buildShows(TV_NETS, TV_RUNS) : []);

